#!/usr/bin/env python3
"""
Train + prune + INT8-quantise a small MLP and emit hardcoded Verilog weights.

Network   : 64 (8x8 digit) -> 16 (ReLU) -> 10           sklearn digits, offline
Sparsity  : magnitude pruning, then retraining with the mask held fixed
INT8      : symmetric per-tensor weights, unsigned 0..127 activations,
            exact integer bias, integer-only requant (multiply + shift)

Writes:
  rtl/mlp_cfg.vh      `define sizes, accumulator widths, requant constants
  rtl/mlp_weights.vh  localparam weight/bias vectors (included in mlp_core)
  sim/*.hex           test images + golden logits/predictions for the testbench
"""
import os
import numpy as np
from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
M1, N1, N2 = 64, 16, 10           # layer-1: M1 inputs -> N1 ; layer-2: N1 -> N2
KEEP1, KEEP2 = 0.30, 0.50         # fraction of weights kept after pruning
rng = np.random.default_rng(0)

# ------------------------------------------------------------------ data
X, y = load_digits(return_X_y=True)
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, random_state=0, stratify=y)
Xtr_f, Xte_f = Xtr / 16.0, Xte / 16.0
Ytr = np.eye(10)[ytr]

# ------------------------------------------------------------------ tiny numpy MLP
W1 = rng.normal(0, np.sqrt(2 / M1), (N1, M1)); b1 = np.zeros(N1)
W2 = rng.normal(0, np.sqrt(2 / N1), (N2, N1)); b2 = np.zeros(N2)
mask1, mask2 = np.ones_like(W1), np.ones_like(W2)

def forward(Xf):
    h = np.maximum(0, Xf @ W1.T + b1)
    return h, h @ W2.T + b2

def train(epochs, lr=0.05, mom=0.9, wd=1e-4):
    global W1, b1, W2, b2
    v = [np.zeros_like(p) for p in (W1, b1, W2, b2)]
    for _ in range(epochs):
        idx = rng.permutation(len(Xtr_f))
        for s in range(0, len(idx), 32):
            bi = idx[s:s + 32]; xb, yb = Xtr_f[bi], Ytr[bi]
            z1 = xb @ W1.T + b1; h = np.maximum(0, z1)
            z2 = h @ W2.T + b2
            p = np.exp(z2 - z2.max(1, keepdims=True)); p /= p.sum(1, keepdims=True)
            d2 = (p - yb) / len(bi)
            gW2 = d2.T @ h + wd * W2; gb2 = d2.sum(0)
            d1 = (d2 @ W2) * (z1 > 0)
            gW1 = d1.T @ xb + wd * W1; gb1 = d1.sum(0)
            for k, (prm, g) in enumerate(zip((W1, b1, W2, b2), (gW1, gb1, gW2, gb2))):
                v[k] = mom * v[k] - lr * g
                prm += v[k]
            W1 *= mask1; W2 *= mask2                # keep pruned weights at 0

acc = lambda Xf, yy: (forward(Xf)[1].argmax(1) == yy).mean()

train(120)
dense_acc = acc(Xte_f, yte)

def prune(W, keep):
    thr = np.quantile(np.abs(W), 1 - keep)
    return (np.abs(W) >= thr).astype(float)

mask1, mask2 = prune(W1, KEEP1), prune(W2, KEEP2)
W1 *= mask1; W2 *= mask2
train(120, lr=0.02)
sparse_acc = acc(Xte_f, yte)

# ------------------------------------------------------------------ INT8 quantisation
def q8(W):
    s = np.abs(W).max() / 127.0
    return np.clip(np.round(W / s), -127, 127).astype(np.int64), s

s_x = 1.0 / 127.0
quant_x = lambda Xraw: np.clip(np.round(Xraw / 16.0 * 127), 0, 127).astype(np.int64)
W1q, s_w1 = q8(W1)
W2q, s_w2 = q8(W2)
b1q = np.round(b1 / (s_x * s_w1)).astype(np.int64)
h_cal, _ = forward(Xtr_f)
s_h = h_cal.max() / 127.0
b2q = np.round(b2 / (s_h * s_w2)).astype(np.int64)

ratio = s_x * s_w1 / s_h               # requant: acc * ratio ~= (acc * RQ_M) >> RQ_SH
RQ_SH = 0
while ratio * (1 << RQ_SH) < (1 << 14):
    RQ_SH += 1
RQ_M = int(round(ratio * (1 << RQ_SH)))
assert (1 << 14) <= RQ_M < (1 << 15)

def requant(a):                        # mirrors rtl/requant.v bit-for-bit
    a = np.maximum(a, 0)
    return np.minimum((a * RQ_M + (1 << (RQ_SH - 1))) >> RQ_SH, 127)

def infer(xq):
    h = requant(W1q @ xq + b1q)
    lg = W2q @ h + b2q
    return lg, int(np.argmax(lg))      # argmax: first max wins (same as RTL)

Xq = quant_x(Xte)
LG, PR = zip(*(infer(x) for x in Xq))
LG, PR = np.array(LG), np.array(PR)
int_acc = (PR == yte).mean()

# ------------------------------------------------------------------ accumulator widths
# worst case of every partial sum along a chain: |bias| + sum |w| * 127
def acc_bits(Wq, bq):
    bound = (np.abs(bq) + np.abs(Wq).sum(1) * 127).max()
    return int(np.ceil(np.log2(bound + 1))) + 1      # +1 sign bit
ACC1, ACC2 = acc_bits(W1q, b1q), acc_bits(W2q, b2q)

# ------------------------------------------------------------------ emit Verilog
def hexvec(vals, bits):
    """Pack vals so element k sits at bits [k*bits +: bits]."""
    word = 0
    for k, v in enumerate(vals):
        word |= (int(v) & ((1 << bits) - 1)) << (k * bits)
    return f"{len(vals) * bits}'h{word:0{len(vals) * bits // 4}x}"

with open(os.path.join(ROOT, "rtl", "mlp_cfg.vh"), "w") as f:
    f.write(f"""// generated by model/gen.py -- do not edit
`ifndef MLP_CFG_VH
`define MLP_CFG_VH
`define M1    {M1}      // layer-1 inputs  (systolic chain length, layer 1)
`define N1    {N1}      // layer-1 neurons (number of chains, layer 1)
`define N2    {N2}      // layer-2 neurons (chain length of layer 2 = N1)
`define ACC1  {ACC1}      // psum width, layer 1 (worst-case bound, not 32)
`define ACC2  {ACC2}      // psum width, layer 2
`define RQ_M  {RQ_M}
`define RQ_SH {RQ_SH}
`endif
""")

with open(os.path.join(ROOT, "rtl", "mlp_weights.vh"), "w") as f:
    f.write("// generated by model/gen.py -- do not edit\n")
    f.write("// W1[(i*M1+j)*8 +: 8] = weight of input j into neuron i (int8, two's complement)\n")
    f.write(f"localparam [{M1*N1*8-1}:0] W1 = {hexvec(W1q.ravel(), 8)};\n")
    f.write(f"localparam [{N1*N2*8-1}:0] W2 = {hexvec(W2q.ravel(), 8)};\n")
    f.write("// biases, 32-bit two's complement per neuron (truncated to ACCn in RTL)\n")
    f.write(f"localparam [{N1*32-1}:0] B1 = {hexvec(b1q, 32)};\n")
    f.write(f"localparam [{N2*32-1}:0] B2 = {hexvec(b2q, 32)};\n")

SIM = os.path.join(ROOT, "sim")
with open(os.path.join(SIM, "x_img.hex"), "w") as f:          # one image per line
    for x in Xq:
        f.write(hexvec(x, 8).split("'h")[1] + "\n")
with open(os.path.join(SIM, "gold_logits.hex"), "w") as f:
    for v in LG.ravel():
        f.write(f"{int(v) & 0xffffffff:08x}\n")
with open(os.path.join(SIM, "gold_pred.hex"), "w") as f:
    for v in PR: f.write(f"{v:02x}\n")
with open(os.path.join(SIM, "label.hex"), "w") as f:
    for v in yte: f.write(f"{v:02x}\n")
with open(os.path.join(SIM, "ntest.vh"), "w") as f:
    f.write(f"`define NTEST {len(Xq)}\n")

nz1, nz2 = int((W1q != 0).sum()), int((W2q != 0).sum())
print(f"float dense accuracy   : {dense_acc*100:.2f}%")
print(f"float pruned accuracy  : {sparse_acc*100:.2f}%")
print(f"INT8 pruned accuracy   : {int_acc*100:.2f}%  ({len(Xq)} test images)")
print(f"layer1 multipliers     : {nz1} of {M1*N1} PEs  ({100-nz1/(M1*N1)*100:.1f}% pruned)")
print(f"layer2 multipliers     : {nz2} of {N1*N2} PEs  ({100-nz2/(N1*N2)*100:.1f}% pruned)")
print(f"accumulator widths     : ACC1={ACC1}  ACC2={ACC2}  (instead of 32)")
print(f"requant                : RQ_M={RQ_M}  RQ_SH={RQ_SH}")
